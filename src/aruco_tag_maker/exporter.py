"""Write a tag set to a folder: STLs, PNGs, markers.json and markers.py."""

from __future__ import annotations

import json
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

from . import __version__
from .marker import write_png
from .mesh import build_tile, write_stl
from .settings import Settings, validate_names

Progress = Callable[[int, int, str], None]


@dataclass
class ExportResult:
    folder: Path
    files: list[Path] = field(default_factory=list)
    tags: dict[str, int] = field(default_factory=dict)


def assign_ids(names: list[str], settings: Settings) -> dict[str, int]:
    """Tag i gets id start_id + i, in the order the names were given."""
    return {name: settings.start_id + index for index, name in enumerate(names)}


def planned_files(names: list[str], folder: Path) -> list[Path]:
    paths = [folder / "markers.json", folder / "markers.py"]
    for name in names:
        paths += [
            folder / "stl" / f"{name}.stl",
            folder / "stl" / "multi-material" / f"{name}_white.stl",
            folder / "stl" / "multi-material" / f"{name}_black.stl",
            folder / "png" / f"{name}.png",
        ]
    return paths


def existing_conflicts(names: list[str], folder: Path) -> list[Path]:
    """Files an export would overwrite."""
    return [path for path in planned_files(names, Path(folder)) if path.exists()]


def manifest(names: list[str], settings: Settings) -> dict:
    ids = assign_ids(names, settings)
    return {
        "generator": f"aruco-tag-maker {__version__}",
        "dictionary": settings.dictionary,
        "tag_size_mm": round(settings.tag_size_mm, 6),
        "tile_size_mm": round(settings.tile_size_mm, 6),
        "quiet_zone_modules": settings.quiet_zone_modules,
        "tags": {name: {"id": marker_id} for name, marker_id in ids.items()},
        "notes": {
            "tag_size_mm": "Side of the black square. Use it as markerLength for pose estimation.",
            "tile_size_mm": "Outer printed tile including the white quiet zone.",
        },
        "print": {
            "base_thickness_mm": settings.base_thickness_mm,
            "relief_mm": settings.relief_mm,
            "total_height_mm": round(settings.total_height_mm, 6),
            "filament_swap_z_mm": settings.base_thickness_mm,
            "name_engraved_on_back": settings.engrave_names,
            "engrave_depth_mm": settings.engrave_depth_mm if settings.engrave_names else 0.0,
        },
        "settings": settings.to_dict(),
    }


MARKERS_PY_TEMPLATE = '''"""ArUco tag names for this set. Generated by {generator}.

    import markers
    markers.MARKERS["{example}"]  # -> {example_id}
    markers.ID_TO_NAME[{example_id}]  # -> "{example}"
    markers.detect(frame)  # -> ["{example}", ...]  (needs opencv-python)
"""

DICTIONARY = {dictionary!r}
TAG_SIZE_MM = {tag_size!r}  # black square side; use as markerLength for pose
TILE_SIZE_MM = {tile_size!r}  # printed tile incl. white quiet zone

MARKERS = {{
{entries}
}}

ID_TO_NAME = {{marker_id: name for name, marker_id in MARKERS.items()}}

try:  # OpenCV is optional: the tables above work without it.
    import cv2 as _cv2
except ImportError:  # pragma: no cover - depends on the environment
    _cv2 = None


def _require_cv2():
    if _cv2 is None:
        raise ImportError("detect() needs OpenCV: pip install opencv-python")
    return _cv2


def get_dictionary():
    cv2 = _require_cv2()
    return cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, DICTIONARY))


def detect(image, with_corners=False):
    """Detect this set's tags in an image (BGR or grayscale numpy array).

    Returns a list of names, or (name, corners) pairs with ``with_corners=True``.
    Markers from the same dictionary that are not in this set are ignored.
    """
    cv2 = _require_cv2()
    detector = cv2.aruco.ArucoDetector(get_dictionary(), cv2.aruco.DetectorParameters())
    corners, ids, _rejected = detector.detectMarkers(image)
    found = []
    if ids is None:
        return found
    for marker_corners, marker_id in zip(corners, ids.flatten()):
        name = ID_TO_NAME.get(int(marker_id))
        if name is None:
            continue
        found.append((name, marker_corners.reshape(4, 2)) if with_corners else name)
    return found
'''


def markers_py(names: list[str], settings: Settings) -> str:
    ids = assign_ids(names, settings)
    example = names[0]
    example_id = ids[example]
    entries = "\n".join(f"    {name!r}: {marker_id}," for name, marker_id in ids.items())
    return MARKERS_PY_TEMPLATE.format(
        generator=f"aruco-tag-maker {__version__}",
        example=example,
        example_id=example_id,
        dictionary=settings.dictionary,
        tag_size=round(settings.tag_size_mm, 6),
        tile_size=round(settings.tile_size_mm, 6),
        entries=entries,
    )


def export(
    names: list[str],
    settings: Settings,
    folder: Path | str,
    *,
    overwrite: bool = False,
    progress: Progress | None = None,
) -> ExportResult:
    """Validate, then write everything into ``folder`` (created if needed)."""
    validate_names(names, settings)
    folder = Path(folder).expanduser()
    if folder.exists() and not folder.is_dir():
        raise NotADirectoryError(f"{folder} exists and is not a folder")
    if not overwrite:
        conflicts = existing_conflicts(names, folder)
        if conflicts:
            raise FileExistsError(
                f"{len(conflicts)} file(s) already exist in {folder}, e.g. {conflicts[0].name}"
            )
    (folder / "stl" / "multi-material").mkdir(parents=True, exist_ok=True)
    (folder / "png").mkdir(parents=True, exist_ok=True)

    ids = assign_ids(names, settings)
    result = ExportResult(folder=folder, tags=dict(ids))
    total = len(names)
    for done, (name, marker_id) in enumerate(ids.items()):
        if progress:
            progress(done, total, name)
        meshes = build_tile(settings, marker_id, name)
        targets = (
            (folder / "stl" / f"{name}.stl", meshes.combined),
            (folder / "stl" / "multi-material" / f"{name}_white.stl", meshes.white),
            (folder / "stl" / "multi-material" / f"{name}_black.stl", meshes.black),
        )
        for path, body in targets:
            write_stl(path, body, f"{name} id {marker_id} {settings.dictionary}")
            result.files.append(path)
        png = folder / "png" / f"{name}.png"
        write_png(png, settings, marker_id)
        result.files.append(png)

    json_path = folder / "markers.json"
    json_path.write_text(json.dumps(manifest(names, settings), indent=2) + "\n", encoding="utf-8")
    py_path = folder / "markers.py"
    py_path.write_text(markers_py(names, settings), encoding="utf-8")
    result.files += [json_path, py_path]
    if progress:
        progress(total, total, "done")
    return result
